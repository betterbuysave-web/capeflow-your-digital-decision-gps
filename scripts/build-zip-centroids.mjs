// Builds lib/data/zipCentroids.ts from the us-zips package (US Census ZCTA
// centroids). Run: node scripts/build-zip-centroids.mjs
// The table lets "Use my location" turn GPS into a ZIP code on the device,
// so exact coordinates never leave the phone.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const zips = require('us-zips');

const rows = Object.entries(zips)
  .map(([zip, { latitude, longitude }]) => [
    Number(zip),
    Math.round(latitude * 100),
    Math.round(longitude * 100),
  ])
  .sort((a, b) => a[0] - b[0]);

// Delta-encode each column, then base-36, comma-separated: zipΔ,latΔ,lngΔ;...
let pz = 0,
  pa = 0,
  po = 0;
const parts = rows.map(([z, a, o]) => {
  const s = [z - pz, a - pa, o - po].map((n) => n.toString(36)).join(',');
  pz = z;
  pa = a;
  po = o;
  return s;
});

const out = `/* Generated by scripts/build-zip-centroids.mjs — do not edit by hand.
 * ${rows.length} US ZIP Code Tabulation Area centroids (US Census Bureau, public
 * domain, via the us-zips package). Encoding: per row "zipΔ,latΔ,lngΔ" in base
 * 36, rows joined by ";", lat/lng in hundredths of a degree (~1 km). */
export const ZIP_CENTROIDS = '${parts.join(';')}';
`;
writeFileSync(new URL('../lib/data/zipCentroids.ts', import.meta.url), out);
console.log(rows.length, 'zips,', (out.length / 1024).toFixed(0), 'KB');
